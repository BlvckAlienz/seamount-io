    print("  4. For RED alerts: click 'View STR Report' to show the AI explanation")

    input(f"\n  Ready? Press ENTER to begin setup...\n")

    await _setup_demo(db)

    input("  Setup complete. Press ENTER to start the demo...\n")

    for scenario in DEMO_SCENARIOS:
        tx    = scenario["tx"]
        step  = scenario["step"]
        total = len(DEMO_SCENARIOS)

        print(f"\n  {DDIVIDER}")
        print(f"  SCENARIO {step} of {total}  —  {scenario['title'].upper()}")
        print(f"  {DDIVIDER}")

        print(f"\n  WHAT TO SAY:")
        for sentence in scenario["pitch"].replace("\n", " ").split(". "):
            s = sentence.strip().rstrip(".")
            if s:
                print(f"    › {s}.")

        print(f"\n  TRANSACTION:")
        print(f"    Amount   : {tx['amount']:,} {tx['asset']}")
        print(f"    Chain    : {tx['chain'].upper()}")
        print(f"    Memo     : \"{tx['memo']}\"")
        print()

        input("  Press ENTER to score...\n")

        print("  ⏳ Embedding transaction via QVAC GTE-Large (1024-dim)...")
        result = await score_transaction(tx, db)

        if not result:
            print("  ❌ Scoring failed — check QVAC (qvac serve) and DB connection")
            input("\n  Press ENTER to continue...\n")
            continue

        band  = result["band"]
        score = result["combined_score"]
        pat   = result.get("matched_pattern_label", "N/A")
        sim   = result.get("pattern_similarity", 0)

        print(f"\n  {DIVIDER}")
        print(f"  RESULT:  {_band_label(band)}")
        print(f"  Score :  {score:.3f} / 1.000")
        print(f"  Match :  \"{pat}\"  ({sim:.1%} cosine similarity)")
        print(f"  {DIVIDER}")

        factors = result.get("factors", {})
        print("\n  FACTOR BREAKDOWN:")
        for k, v in sorted(factors.items(), key=lambda x: -x[1]["score"]):
            bar   = "█" * int(v["score"] * 24) + "░" * (24 - int(v["score"] * 24))
            fired = "  ← FIRED" if v["score"] >= 0.25 else ""
            print(f"    {k:<26} [{bar}] {v['score']:.2f}{fired}")

        if result.get("str_explanation"):
            print(f"\n  {'─'*64}")
            if band == "RED":
                print("  AI-GENERATED SUSPICIOUS TRANSACTION REPORT (Qwen3-600M):")
            else:
                print("  COMPLIANCE NOTE (template — no LLM for AMBER band):")
            print(f"  {'─'*64}")
            for line in result["str_explanation"].split("\n"):
                print(f"  {line}")
            print(f"  {'─'*64}")

        print()
        print(f"  ► NOW: Click REFRESH in the Admin Dashboard.")
        if band == "RED":
            print(f"  ► Click 'View STR Report' on the 🔴 RED alert card.")
            print(f"  ► Point out: every claim in the STR is traceable to a verified DB fact.")
        else:
            print(f"  ► Show the 🟡 AMBER card — the engine flagged but deferred to a human.")
            print(f"  ► Point out: 'The system knows its own limits. That is a feature.'")

        if step < total:
            input(f"\n  Press ENTER for Scenario {step + 1}...\n")

