async def run_demo():
    db = get_database_service()

    print(f"\n{DDIVIDER}")
    print("   SEAMOUNT.IO — LIVE AML INTELLIGENCE DEMO")
    print("   Real-time AI-powered fraud detection | Nigeria & Kenya")
