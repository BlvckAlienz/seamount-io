DIVIDER  = "─" * 68
DDIVIDER = "═" * 68


def _band_label(band: str) -> str:
    return {"RED": "🔴  RED", "AMBER": "🟡  AMBER", "GREEN": "✅  GREEN"}.get(band, "❓")


# ─────────────────────────────────────────────────────────────────────────
# SETUP — clears old alerts and seeds prior fraud for counterparty trigger
# ─────────────────────────────────────────────────────────────────────────
async def _setup_demo(db):
    print(f"\n  {DIVIDER}")
    print("  SETUP — Preparing demo environment...")
    print(f"  {DIVIDER}")

    # 1. Clear all previous demo and seed records
    for prefix in ['demo_%', 'prior_fraud_%']:
        try:
            db.supabase.table('aml_audit_log').delete().like('tx_id', prefix).execute()
            db.supabase.table('aml_risk_scores').delete().like('tx_id', prefix).execute()
        except Exception as e:
            print(f"  ⚠️  Cleanup warning (non-fatal): {e}")
    print("  ✅ Previous demo alerts cleared")

    # 2. Seed a confirmed_fraud record for _RED_RECIPIENT (3 days ago)
    #    This makes counterparty_risk = 1.0 for any transaction to that address,
    #    adding 0.15 to the score and pushing gold scam from 0.60 → 0.75 (RED).
    try:
        db.supabase.table('aml_risk_scores').insert({
            'tx_id':                 'prior_fraud_gold_scam_seed',
            'user_id':               '00000000-0000-0000-0000-000000000099',
            'recipient_address':     _RED_RECIPIENT,
            'combined_score':        0.94,
            'band':                  'RED',
            'status':                'confirmed_fraud',
            'matched_pattern_label': 'Gold Scam with POCAMLA Laundering',
            'pattern_similarity':    0.94,
            'ofac_match':            False,
            'factors':               {},
            'scoring_version':       '1.0.0',
            'created_at': (datetime.utcnow() - timedelta(days=3)).isoformat(),
        }).execute()
        print(f"  ✅ Prior confirmed-fraud record seeded for recipient")
        print(f"     → counterparty_risk will score 1.0 for Scenarios 1–3")
    except Exception as e:
        print(f"  ⚠️  Seed warning: {e}")

    print(f"  {DIVIDER}\n")


